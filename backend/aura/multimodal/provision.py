def main(argv: Optional[list[str]] = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description="Provision AURA Docling model cache for offline use.")
    parser.add_argument("--cache", default="",
                        help="model cache dir (default: $AURA_DOCS_MODEL_CACHE"
                             " or $AURA_HOME/models/docling)")
    parser.add_argument("--ocr", default="auto",
                        help="ocr engine to warm (auto|rapidocr|tesseract|none)")
    parser.add_argument("--no-samples", action="store_true",
                        help="record manifest without warming conversions")
    args = parser.parse_args(argv)
    try:
        report = provision(
            cache=Path(args.cache).expanduser() if args.cache else None,
            ocr_engine=args.ocr,
            include_samples=not args.no_samples)
    except Exception as exc:
        print(f"provisioning failed: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
