/**
 * agent/journal — the loop's own execution record.
 * ==================================================================
 * NOT a second audit sink, and the distinction matters enough to be
 * precise about:
 *
 *   The Capability Fabric's audit trail is the authority on what RAN, on
 *   whose authority, and whether it worked. Every action a run takes
 *   produces exactly one `AuditRecord`, written by `settle()`, and this
 *   journal never restates one — its `tool.result` entries carry the
 *   `invocationId` and point at it.
 *
 *   What lives here and nowhere else is the loop's own control flow: what
 *   the model said, what it asked for, what was refused before it ever
 *   reached the Fabric, which bound was hit, when the switch was pulled.
 *   None of that is an action, so none of it belongs in an action log.
 *
 * The relationship is the one Mission Control's timeline already has with
 * the same audit trail: two records, two questions, one authority each.
 *
 * Storage reuses the existing config home and the existing atomic
 * write-then-rename from `persist.ts` — the same mechanism `MissionStore`,
 * `policyStore` and `approvalStore` use. No new database, no second
 * persistence system.
 *
 *   ~/.aura/agent-runs/<runId>.json      (AURA_HOME aware)
 *
 * One file per run, appended in place. A run is a bounded thing that ends;
 * a single growing log would make reading one run mean reading all of
 * them, and would make deleting one mean rewriting the rest.
 */

import fs from 'node:fs';
import type { AgentJournal, AgentJournalEntry } from './types';
import { homePath, readJsonFile, writeJsonFile } from '../persist';

const DIR = () => homePath('agent-runs');
const FILE = (runId: string) => homePath('agent-runs', `${safeRunId(runId)}.json`);

/**
 * A run id is generated by this module, but the journal is also read back
 * by id from callers that got theirs from a request. Anything that is not
 * a plain id is refused rather than sanitised into a neighbouring path —
 * silently rewriting a traversal attempt into a valid filename is how you
 * end up unable to explain which file was written.
 */
function safeRunId(runId: string): string {
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(runId)) {
    throw new Error(`"${runId}" is not a valid run id.`);
  }
  return runId;
}

let counter = 0;

/** A fresh run id. Sortable by time, unique within a process. */
export function newRunId(prefix = 'run'): string {
  counter += 1;
  return `${prefix}-${Date.now().toString(36)}-${counter.toString(36)}`;
}

/**
 * An in-memory journal.
 *
 * `durable: false`, which is what makes it unusable for a real run: the
 * agent-loop gate refuses to arm without durability, so this exists for
 * tests and for reasoning about the loop, not for running it.
 */
export class MemoryAgentJournal implements AgentJournal {
  readonly durable = false;
  private entries = new Map<string, AgentJournalEntry[]>();
  private order: string[] = [];

  append(entry: AgentJournalEntry): void {
    const existing = this.entries.get(entry.runId);
    if (existing) existing.push(entry);
    else {
      this.entries.set(entry.runId, [entry]);
      this.order.unshift(entry.runId);
    }
  }

  read(runId: string): AgentJournalEntry[] {
    return [...(this.entries.get(runId) ?? [])].sort((a, b) => a.seq - b.seq);
  }

  runs(): string[] {
    return [...this.order];
  }
}

/**
 * A journal on disk.
 *
 * Writes the whole run file on every append. That is O(n²) over a run's
 * entries and it is the right trade at this size: a run is capped at 40
 * iterations and 200 tool calls by `HARD_CEILING`, so the file is a few
 * hundred small objects, and the alternative — an append-only text stream
 * — would need its own reader, its own corruption handling and its own
 * atomicity story to replace one that already exists and is already used
 * by three other stores.
 */
export class FileAgentJournal implements AgentJournal {
  readonly durable = true;
  private cache = new Map<string, AgentJournalEntry[]>();

  append(entry: AgentJournalEntry): void {
    const runId = safeRunId(entry.runId);
    const entries = this.cache.get(runId) ?? this.load(runId);
    entries.push(entry);
    this.cache.set(runId, entries);
    writeJsonFile(FILE(runId), entries);
  }

  read(runId: string): AgentJournalEntry[] {
    return [...(this.cache.get(safeRunId(runId)) ?? this.load(runId))].sort((a, b) => a.seq - b.seq);
  }

  runs(): string[] {
    let names: string[];
    try {
      names = fs.readdirSync(DIR());
    } catch {
      // No directory yet is "no runs", not an error. A first run must not
      // have to be preceded by a successful read.
      return [];
    }
    return names
      .filter((n) => n.endsWith('.json'))
      .map((n) => ({ id: n.slice(0, -5), mtime: mtimeOf(homePath('agent-runs', n)) }))
      .sort((a, b) => b.mtime - a.mtime)
      .map((r) => r.id);
  }

  private load(runId: string): AgentJournalEntry[] {
    const raw = readJsonFile<AgentJournalEntry[]>(FILE(runId), []);
    return Array.isArray(raw) ? raw : [];
  }
}

function mtimeOf(file: string): number {
  try { return fs.statSync(file).mtimeMs; } catch { return 0; }
}

/** Where run journals live, for anything that needs to tell a user. */
export function journalDirectory(): string {
  return DIR();
}

/**
 * A sequence-numbering writer around a journal.
 *
 * The sequence is per-run and assigned here so entry order is a property
 * of the record rather than of the file it happened to land in — a
 * reconstruction reads `seq`, not array position, and two writers cannot
 * silently interleave into a plausible-looking wrong order.
 */
export class RunJournalWriter {
  private seq = 0;

  constructor(private readonly journal: AgentJournal, readonly runId: string) {}

  get durable(): boolean { return this.journal.durable; }

  write<T extends AgentJournalEntry['type']>(
    type: T,
    fields: Omit<Extract<AgentJournalEntry, { type: T }>, 'type' | 'seq' | 'at' | 'runId'>,
  ): void {
    this.seq += 1;
    this.journal.append({
      type,
      seq: this.seq,
      at: new Date().toISOString(),
      runId: this.runId,
      ...fields,
      // The discriminated union is reassembled from a type parameter and a
      // matching field set, which TypeScript cannot verify structurally.
      // The `Omit` on the parameter is what actually enforces correctness
      // at every call site; this cast only restates it.
    } as unknown as AgentJournalEntry);
  }

  entries(): AgentJournalEntry[] {
    return this.journal.read(this.runId);
  }
}

