/**
 * Rebuild a run from its journal alone.
 *
 * This is the test of whether the journal is worth having. If a run can
 * be described completely from the file — the objective, the bounds it
 * ran under, every turn, every refusal, every action and its audit id,
 * and how it ended — then "reproducible from the journal" is a fact
 * rather than an aspiration, and `scripts/agent-loop-verify.mjs` checks
 * it by reading a file it did not write.
 */
export interface ReconstructedRun {
  runId: string;
  objective: string;
  systemPrompt: string;
  level: number;
  scope: readonly string[];
  policy: string;
  model: string;
  /** The message list as it stood at the end, rebuilt from the entries. */
  transcript: { role: 'system' | 'user' | 'assistant' | 'tool'; content: string }[];
  actions: { capabilityId: string; invocationId: string; outcome: string }[];
  refusals: { requestedName: string; rule: string }[];
  limitsHit: { limit: string; observed: number; cap: number }[];
  killed: { by: string; reason: string } | null;
  outcome: string | null;
  answer: string;
  complete: boolean;
}

export function reconstructRun(entries: AgentJournalEntry[]): ReconstructedRun | null {
  const ordered = [...entries].sort((a, b) => a.seq - b.seq);
  const started = ordered.find((e) => e.type === 'run.started');
  if (!started || started.type !== 'run.started') return null;

  const transcript: ReconstructedRun['transcript'] = [
    { role: 'system', content: started.systemPrompt },
    { role: 'user', content: started.objective },
  ];
  const actions: ReconstructedRun['actions'] = [];
  const refusals: ReconstructedRun['refusals'] = [];
  const limitsHit: ReconstructedRun['limitsHit'] = [];
  let killed: ReconstructedRun['killed'] = null;
  let outcome: string | null = null;
  let answer = '';

  for (const entry of ordered) {
    switch (entry.type) {
      case 'model.turn':
        transcript.push({
          role: 'assistant',
          content: entry.requested.length
            ? `${entry.text}\n[requested: ${entry.requested.map((r) => r.name).join(', ')}]`
            : entry.text,
        });
        break;
      case 'tool.result':
        transcript.push({ role: 'tool', content: entry.observation });
        actions.push({ capabilityId: entry.capabilityId, invocationId: entry.invocationId, outcome: entry.outcome });
        break;
      case 'tool.refused':
        transcript.push({ role: 'tool', content: `${entry.rule}: ${entry.reason}` });
        refusals.push({ requestedName: entry.requestedName, rule: entry.rule });
        break;
      case 'limit.reached':
        limitsHit.push({ limit: entry.limit, observed: entry.observed, cap: entry.cap });
        break;
      case 'kill':
        killed = { by: entry.by, reason: entry.reason };
        break;
      case 'run.finished':
        outcome = entry.outcome;
        answer = entry.answer;
        break;
      default:
        break;
    }
  }

  return {
    runId: started.runId,
    objective: started.objective,
    systemPrompt: started.systemPrompt,
    level: started.level,
    scope: started.scope,
    policy: started.policy,
    model: started.model,
    transcript,
    actions,
    refusals,
    limitsHit,
    killed,
    outcome,
    answer,
    // A run with no `run.finished` was interrupted at a level the journal
    // could not record — a crash, a kill -9. Saying so is more useful than
    // presenting a partial run as a whole one.
    complete: outcome !== null,
  };
}
